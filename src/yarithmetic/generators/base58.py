"""Base58 candidate detection, decoding, and experimental Base58Check circuits."""

from yarithmetic.generators.compatibility import (
    parse_output_version,
    repeat_atom,
    require_runtime_candidate_selection,
)


BASE58_REGEX = "[1-9A-HJ-NP-Za-km-z]"
MAX_LENGTH = 128


def generate_charset_value(byte_expression: str) -> str:
    """Map a byte already checked against the Bitcoin Base58 alphabet to 0..57.

    The arithmetic is deliberately undefined for bytes outside that alphabet.
    """
    byte = f"({byte_expression})"
    # Subtract the gaps before each alphabet segment. Comparisons are encoded
    # arithmetically because YARA does not coerce booleans into integers.
    # All input bytes are ASCII, so (byte + 128 - threshold) >> 7 is 0 or 1.
    def at_least(threshold):
        return f"(({byte} + {128 - threshold}) >> 7)"

    return (
        f"({byte} - 49"
        f" - 7 * {at_least(65)}"
        f" - {at_least(74)}"
        f" - {at_least(80)}"
        f" - 6 * {at_least(97)}"
        f" - {at_least(109)})"
    )


def generate_decoded_word(
    candidate_offset: str,
    candidate_length: int,
    word_index: int = 0,
) -> str:
    """Emit a 32-bit word of the decoded integer, least-significant word first.

    Input must already be constrained to exactly candidate_length Base58 bytes.
    Leading '1' characters contribute zero to the integer; preserving their
    corresponding zero bytes requires separate decoded-length handling.
    """
    if not 1 <= candidate_length <= MAX_LENGTH:
        raise ValueError("candidate_length must be between 1 and 128")
    max_words = ((58 ** candidate_length - 1).bit_length() + 31) // 32
    if not 0 <= word_index < max_words:
        raise ValueError("word_index is outside the decoded integer")

    # Expand N = sum(digit[i] * 58**(length-1-i)) into base-2**32
    # coefficient columns. Propagate carry from each lower column. Each sum
    # is bounded by 128 * 57 * (2**32 - 1) plus carry, safely below 2**63.
    carry = None
    for column in range(word_index + 1):
        terms = []
        for offset in range(candidate_length):
            coefficient = (
                58 ** (candidate_length - offset - 1) >> (32 * column)
            ) & 0xFFFFFFFF
            if coefficient:
                digit = generate_charset_value(
                    f"uint8(({candidate_offset}) + {offset})"
                )
                terms.append(f"({digit} * {hex(coefficient)})")
        if carry is not None:
            terms.append(f"(({carry}) >> 32)")
        carry = " + ".join(terms) or "0"
    return f"(({carry}) & 0xffffffff)"


def generate_base58_candidate_rule(
    min_length: int = 26,
    max_length: int = 35,
    *,
    output_version=None,
) -> str:
    """Generate alphabet/length detection only, with alphanumeric boundaries.

    Defaults cover common legacy Bitcoin address lengths. This also matches
    ordinary words of sufficient length and checksum-invalid addresses.
    A 3.4 target uses fixed-length private rules instead of match lengths.
    """
    if not 1 <= min_length <= max_length <= MAX_LENGTH:
        raise ValueError("lengths must satisfy 1 <= min <= max <= 128")

    version = parse_output_version(output_version)
    if version is not None and version < (3, 5, 0):
        # Match lengths were introduced in 3.5. Use a separate fixed-length
        # candidate rule per length so no runtime length lookup is needed.
        rules = []
        names = []
        for length in range(min_length, max_length + 1):
            name = f"Base58_Candidate_Length{length}"
            source = generate_base58_candidate_rule(length, length)
            source = source.replace("rule Base58_Candidate", f"private rule {name}")
            rules.append(source.replace("!candidate[i]", str(length)))
            names.append(name)
        rules.append("rule Base58_Candidate { condition: " + " or ".join(names) + " }\n")
        return "".join(rules)

    # An ASCII alphanumeric boundary rejects substrings next to excluded
    # characters (0, O, I, l), as well as prefixes of overlong Base58 tokens.
    def boundary(position):
        byte = f"uint8({position})"
        return (
            f"({byte} < 48 or {byte} > 57) and "
            f"({byte} < 65 or {byte} > 90) and "
            f"({byte} < 97 or {byte} > 122)"
        )

    pattern = repeat_atom(BASE58_REGEX, min_length, max_length, output_version)
    if version is None or version[:2] != (3, 6):
        pattern = f"{BASE58_REGEX}{{{min_length},{max_length}}}"

    return f"""// Generated by yarithmetic.generators.base58.generate_base58_candidate_rule
// Candidate detection only: NO Base58Check checksum validation.
rule Base58_Candidate
{{
    strings:
        $candidate = /{pattern}/
    condition:
        for any i in (1..#candidate) : (
            (@candidate[i] == 0 or ({boundary('@candidate[i] - 1')}))
            and
            (@candidate[i] + !candidate[i] >= filesize or
                ({boundary('@candidate[i] + !candidate[i]')}))
        )
}}
"""


def generate_base58check_p2pkh_rule(candidate_index: int = 1, *, output_version=None) -> str:
    """Experimental checksum validation for one slot of 34-character P2PKH.

    Supports exactly one leading '1' (a zero version byte), followed by a
    nonzero 24-byte decoded integer. Does not cover every Bitcoin address.
    candidate_index selects a regex occurrence, not the Nth valid address.
    Each slot requires its own Boolean circuit, evaluated once per file.
    """
    if not 1 <= candidate_index <= 16:
        raise ValueError("candidate_index must be between 1 and 16")
    return _generate_base58check_p2pkh_rule(candidate_index, output_version=output_version)


def generate_base58check_p2pkh_parameterized_rule(*, output_version=None) -> str:
    """Validate one runtime-selected occurrence using an external integer.

    Define candidate_index as an integer when compiling, then set it for each
    scan. Positive indices select raw regex occurrences, including embedded or
    checksum-invalid candidates. A missing or nonpositive slot never matches.
    This evaluates one candidate per scan, not every candidate in a file.
    Requires YARA 3.5 or later; output_version enables release workarounds.
    """
    require_runtime_candidate_selection(output_version)
    return _generate_base58check_p2pkh_rule("candidate_index", parameterized=True, output_version=output_version)


def _generate_base58check_p2pkh_rule(candidate_index, parameterized=False, output_version=None):
    from yarithmetic.generators.sha256 import BooleanCircuit, constant, digest_bytes

    pattern = f"1[2-9A-HJ-NP-Za-km-z]{repeat_atom(BASE58_REGEX, 32, 32, output_version)}"
    strings = f"strings: $candidate = /{pattern}/"
    offset = f"@candidate[{candidate_index}]"
    suffix = "Parameterized" if parameterized else f"Slot{candidate_index}"
    prefix = "b58_parameterized" if parameterized else f"b58_slot{candidate_index}"
    circuit = BooleanCircuit(prefix=prefix)
    words = [generate_decoded_word(offset, 34, index) for index in range(7)]

    def input_bit(bit):
        word, shift = divmod(bit, 32)
        return circuit.input(f"(({words[word]} >> {shift}) & 1) == 1", strings)

    # The decoded 25-byte address is 0x00 | 20-byte payload | 4-byte checksum.
    message = [constant(0, 8)] + [
        [input_bit(32 + (19 - byte) * 8 + bit) for bit in range(8)]
        for byte in range(20)
    ]
    first = circuit.sha256(message)
    second = circuit.sha256(digest_bytes(first))
    checksum_matches = [
        circuit.gate("not", circuit.gate("xor", bit, input_bit(index)))
        for index, bit in enumerate(second[0])
    ]

    def alphanumeric(position):
        byte = f"uint8({position})"
        return (
            f"(({byte} >= 48 and {byte} <= 57) or "
            f"({byte} >= 65 and {byte} <= 90) or "
            f"({byte} >= 97 and {byte} <= 122))"
        )

    condition = "\n        and ".join(checksum_matches)
    generator = "generate_base58check_p2pkh_parameterized_rule" if parameterized else "generate_base58check_p2pkh_rule"
    runtime_guard = "candidate_index >= 1\n        and " if parameterized else ""
    return (
        f"// Generated by yarithmetic.generators.base58.{generator}\n"
        "// Experimental: one candidate slot, 34 characters, one leading zero byte.\n"
        + "".join(circuit.rules)
        + f"""
rule Valid_Base58Check_P2PKH_34_{suffix}
{{
    {strings}
    condition:
        {runtime_guard}#candidate >= {candidate_index}
        and ({offset} == 0 or not {alphanumeric(f'{offset} - 1')})
        and ({offset} + 34 >= filesize or not {alphanumeric(f'{offset} + 34')})
        and {words[6]} == 0
        and {words[5]} >= 0x1000000
        and {condition}
}}
"""
    )
