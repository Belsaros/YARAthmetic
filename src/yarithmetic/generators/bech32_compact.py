"""Shared Bech32 polymod arithmetic with runtime length and separator selection.

Let T(s) = polymod_step(s, 0), n be the candidate length and h the HRP
length. Padding the expanded input with 90-n zero symbols gives

    T**h(H) XOR R == T**(90-n)(encoding_constant)

H contains the initial state and HRP high bits; R contains HRP low bits and
data. Both use fixed coefficient distances, gated by runtime positions. Two
small transition tables apply T**h without exceeding four nested YARA loops.
"""

from yarithmetic.generators.compatibility import repeat_atom, require_match_lengths

from yarithmetic.generators.bech32 import (
    generate_charset_bit,
    generate_hrp_high_value,
    generate_polymod_transition_matrix,
)
from yarithmetic.reference.bech32 import (
    BECH32_CONSTANT,
    BECH32M_CONSTANT,
    polymod_step,
)

MASK = 0x3FFFFFFF


def advance(state, distance):
    for _ in range(distance):
        state = polymod_step(state, 0)
    return state


def generate_lookup(values, index):
    """Select a 30-bit integer using pairs packed into positive 60-bit words.

    index must be in 0..len(values)-1, and len(values) must be at most 128.
    Threshold masks choose exactly one pair; the low index bit selects its half.
    All shifts and arithmetic stay within signed 64-bit YARA integers.
    """
    if not values or len(values) > 128 or any(not 0 <= value <= MASK for value in values):
        raise ValueError("expected 1..128 unsigned 30-bit values")
    terms = []
    for start in range(0, len(values), 2):
        packed = values[start]
        if start + 1 < len(values):
            packed |= values[start + 1] << 30
        if not packed:
            continue
        selected = (
            f"(((({index}) + {256 - start}) >> 8)"
            f" - ((({index}) + {254 - start}) >> 8))"
        )
        terms.append(
            f"((({hex(packed)} >> ((({index}) & 1) * 30)) & {hex(MASK)}) * {selected})"
        )
    return "(" + " + ".join(terms or ["0"]) + ")"


def generate_transition(state, index, steps):
    matrices = [generate_polymod_transition_matrix(step) for step in steps]
    terms = [
        f"(((({state}) >> {bit}) & 1) * "
        f"{generate_lookup([matrix[bit] for matrix in matrices], index)})"
        for bit in range(30)
    ]
    return "(" + " ^ ".join(terms) + ")"


def generate_fixed_inputs(offset, length, hrp):
    high = [hex(advance(1, 90))]
    rest = []
    for position in range(90):
        # Read inside the candidate even for inactive padded positions. An
        # out-of-file uint8 is undefined, and multiplying undefined by zero
        # would still poison the entire XOR expression.
        byte = f"uint8(({offset}) + ({position} % ({length})))"
        is_hrp = f"((({hrp}) + {127 - position}) >> 7)"
        is_data = (
            f"((({position + 127} - ({hrp})) >> 7)"
            f" * ((({length}) + {127 - position}) >> 7))"
        )
        if position < 83:
            value = generate_hrp_high_value(byte)
            for bit in range(2):
                coefficient = advance(1 << bit, 89 - position)
                high.append(f"((((({value}) >> {bit}) & 1) * {is_hrp}) * {hex(coefficient)})")
            for bit in range(5):
                coefficient = advance(1 << bit, 88 - position)
                rest.append(f"((((({byte}) >> {bit}) & 1) * {is_hrp}) * {hex(coefficient)})")
        if position >= 2:
            for bit in range(5):
                coefficient = advance(1 << bit, 89 - position)
                value = generate_charset_bit(byte, bit)
                rest.append(f"((({value}) * {is_data}) * {hex(coefficient)})")
    return "(" + " ^ ".join(high) + ")", "(" + " ^ ".join(rest) + ")"


def generate_compact_bech32_rule(shapes=None, *, output_version=None):
    require_match_lengths(output_version)
    if shapes is not None:
        shapes = sorted(set(shapes))
        if any(not 8 <= n <= 90 or not 1 <= h <= n - 7 for n, h in shapes):
            raise ValueError("expected shapes with 8 <= length <= 90 and 1 <= HRP <= length-7")

    candidate = "i"
    length = f"!candidate[{candidate}]"
    offset = f"@candidate[{candidate}]"
    hrp = "h"
    high, rest = generate_fixed_inputs(offset, length, hrp)
    packed = f"((({high}) << 30) | ({rest}))"
    low_transition = generate_transition("(packed >> 30)", f"({hrp} & 15)", range(16))
    high_transition = generate_transition("shifted", f"({hrp} >> 4)", range(0, 96, 16))
    expected = generate_lookup([advance(BECH32_CONSTANT, d) for d in range(83)], f"(90 - {length})")
    expected_m = generate_lookup(
        [advance(BECH32M_CONSTANT, d) for d in range(83)], f"(90 - {length})"
    )
    allowed_shapes = "true" if shapes is None else (
        " or ".join(f"({length} == {n} and {hrp} == {h})" for n, h in shapes) or "false"
    )
    return f"""// Generated by yarithmetic.generators.bech32_compact.generate_compact_bech32_rule
// Full Bech32/Bech32m checksum validation, all candidate occurrences, lengths 8..90.
rule Bech32_Candidate
{{
    strings:
        $candidate = /[!-~]+1{repeat_atom("[qpzry9x8gf2tvdw0s3jn54khce6mua7l]", 6, None, output_version)}/ nocase
    condition:
        #candidate > 0 and
        for any i in (1..#candidate) : (
            {length} <= 90
            and (
                {offset} == 0 or uint8({offset} - 1) < 33 or uint8({offset} - 1) > 126
            )
            and (
                for all j in (0..{length} - 1) : (
                    uint8({offset} + j) < 97 or uint8({offset} + j) > 122
                )
                or for all j in (0..{length} - 1) : (
                    uint8({offset} + j) < 65 or uint8({offset} + j) > 90
                )
            )
            and for any h in (1..{length} - 7) : (
                uint8({offset} + h) == 49
                and ({allowed_shapes})
                and for all j in (h + 1..{length} - 1) : (
                    uint8({offset} + j) != 49
                )
                and for any packed in ({packed}) : (
                    for any shifted in ({low_transition}) : (
                        (({high_transition}) ^ (packed & {hex(MASK)})) == {expected}
                        or (({high_transition}) ^ (packed & {hex(MASK)})) == {expected_m}
                    )
                )
            )
        )
}}
"""
